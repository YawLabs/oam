#!/bin/bash
# =============================================================================
# The linux leg's hands on the build Mac: a Lima VM, and a container in it.
# =============================================================================
# Runs ON the build Mac, piped there by scripts/build-platforms-mac-linux.sh:
#
#   ssh <mac> 'bash -s -- <verb> <instance> [args...]' < scripts/mac-linux-vm.sh
#
# Piped, never synced, for the reason provision-mac-signing.sh is: the copy on
# the Mac would be a release old, and the preflight runs before any sync. Each
# call is one verb; the orchestrator owns order, logs and failure messages.
#
# What it drives (measured by hand on the build Mac, Lima 2.2.1 from Homebrew,
# before this script existed):
#
#   Lima VM     <instance> (default oam-linux): vz, Rosetta for Linux, Debian 12
#               guest. Its built-in DNS forwarder (192.168.5.2) cannot answer
#               PTR or CAA queries, which the dns conformance cases make, so
#               the host resolver is off and the VM resolves through public
#               servers. Lima still appends the forwarder to the guest's
#               resolv.conf, so the container gets its own resolv.conf naming
#               only the public ones, through a bind mount.
#   container   <instance>-build: debian:12 as linux/amd64, run by the VM's
#               rootless nerdctl (no sudo anywhere) with host networking, so
#               the build is x86_64 code under Rosetta -- the V8 snapshot must
#               be generated by a process of the target architecture (see
#               scripts/build-remote.sh). Debian 12 is the distro the linux
#               asset has always been built on, which keeps the newest GLIBC_
#               symbol the binary needs at 2.34; the orchestrator gates on
#               that after the build. Long-lived: it is created once, its
#               packages baked in, and recreated only when its spec (image,
#               packages, user, mounts -- SPEC_SRC below) changes.
#   home volume <instance>-home, mounted as the build user's home: rustup and
#               the cargo registry, the pinned Node, tsgo, and the build tree
#               ~/oam-build with its target/ all live on the VM's ext4 and
#               survive a stop, a sync and a container rebuild. Lima mounts the
#               Mac home into the VM READ-ONLY, and the Mac's /tmp not at all,
#               so nothing is built on the Mac's disk.
#   build user  builder, uid 1000. Never root: the permission tests (an EACCES
#               a root process would not get) fail as root.
#
# Verbs (all but status and provision need the VM Running; start does that):
#   status                       key=value lines: limactl=<version|missing>,
#                                arch=<uname -m>, rosetta=<yes|no>,
#                                status=<Running|Stopped|...|absent>
#   provision <cpus> <mem-gib> <disk-gib>
#                                create the instance if absent, then (stopped)
#                                set the resolver and size settings; idempotent
#   start | stop                 limactl start / stop, each a no-op when the VM
#                                is already there
#   container                    the container above, created or reused (a
#                                build left running in a reused one is
#                                killed); its resolv.conf and open-file
#                                limit are checked either way
#   sync <tarball>               extract ~/<tarball> (Mac home, relative) into
#                                the build tree, keeping target/; removes it
#   run <dispatch> <node-ver>    bash scripts/build-remote.sh <dispatch> in the
#                                build tree as the build user, with the pinned
#                                Node FIRST on PATH (see do_run), after killing
#                                whatever a cut-off dispatch left running
#   free-gb                      df -BG of the build user's home, for the
#                                orchestrator's disk headroom check
#   glibc <path>                 the GLIBC_ versions objdump -T finds in
#                                ~/oam-build/<path>, one per line
#   fetch <path>                 copy ~/oam-build/<path> out to the Mac as
#                                ~/.oam-linux-leg/out/<basename>; prints
#                                sha256=<container's hash> and path=<that file,
#                                Mac-home relative>
#
# The Mac build lock (shared with the Yaw repo's linux leg, which drives its
# own Lima instance on the same Mac; protocol v1, agreed between the two):
#   lock <runid> <repo> <instance> [<host> <pid>]
#                                take ~/.lima-build.lock for this run; exit 0
#                                acquired, 3 BUSY (the owner on stderr), 1 an
#                                error. <host> and <pid> name the orchestrator
#                                in the owner file (default unknown / 0).
#   unlock <runid>               remove the lock only if its owner is <runid>;
#                                exit 0 released (or no lock), 3 held by
#                                another run (left alone, owner on stderr)
# These two take their own arguments, not <instance> second. See do_lock.
# status also reports others=<other Running instances, comma-separated|none>
# and lock=<none|ownerless|held>, with lock.<key>=<value> per owner line.
#
# Arguments reach this script through the Mac's shell, so the orchestrator
# validates every one first, and this script checks their shape again.
# =============================================================================
set -euo pipefail

# Everything is in main, and main is the last line: bash -s reads the script
# from the same stdin the commands below would inherit, so nothing may run
# until the whole script has been read -- and then stdin goes, so no command
# can swallow what is left of it.
main() {
  exec </dev/null
  # A non-interactive ssh session on the Mac does not read the login profile,
  # so Homebrew's prefix is not on PATH.
  export PATH="/opt/homebrew/bin:/usr/local/bin:$PATH"

  local verb="${1:-}"
  LOCK_DIR="$HOME/.lima-build.lock"
  case "$verb" in
    lock)   shift; do_lock "$@"; return ;;
    unlock) shift; do_unlock "$@"; return ;;
  esac
  INSTANCE="${2:-}"
  [[ "$INSTANCE" =~ ^[A-Za-z0-9]([A-Za-z0-9-]*[A-Za-z0-9])?$ ]] \
    || die "instance name '$INSTANCE' is not letters, digits and inner hyphens"
  CONTAINER="$INSTANCE-build"
  VOLUME="$INSTANCE-home"
  STAGE="$HOME/.oam-linux-leg"
  shift 2

  case "$verb" in
    status)    do_status ;;
    provision) do_provision "$@" ;;
    start)     do_start ;;
    stop)      do_stop ;;
    container) do_container ;;
    sync)      do_sync "$@" ;;
    run)       do_run "$@" ;;
    free-gb)   do_free_gb ;;
    glibc)     do_glibc "$@" ;;
    fetch)     do_fetch "$@" ;;
    *) die "unknown verb '$verb' (want status|provision|start|stop|container|sync|run|free-gb|glibc|fetch|lock|unlock)" ;;
  esac
}

note(){ echo "[mac] $*" >&2; }
die(){  echo "[mac] FATAL: $*" >&2; exit 1; }

# What the container is. Its hash is written into the container last, so a
# container whose setup died half way is rebuilt rather than trusted, and any
# change here rebuilds it on the next run.
IMAGE="debian:12"
# unzip: the bun installer build-remote.sh bench runs needs it, and that
# install is best-effort, so without it a bench quietly loses its bun column.
PACKAGES="build-essential binutils curl ca-certificates git xz-utils python3 pkg-config procps unzip nodejs npm"
BUILD_HOME="/home/builder"
# The open-file limit, set explicitly rather than inherited from rootless
# containerd's user service (soft 1024 there unless something raised it):
# the http_server_wire flood tests need thousands of descriptors, and
# build-remote.sh's own `ulimit -n 4096` can only raise the soft limit up
# to whatever hard limit the container was given.
NOFILE=65536
SPEC_SRC() { printf 'v2|%s|linux/amd64|%s|builder:1000|%s=%s|dns=1.1.1.1,8.8.8.8|net=host|nofile=%s|init=1' \
  "$IMAGE" "$PACKAGES" "$BUILD_HOME" "$VOLUME" "$NOFILE"; }

# The VM-side shell lines that kill whatever the build user (uid 1000) left
# running in the container, and wait for it to go. Killing a `nerdctl exec`
# client -- which is what a dropped ssh or tailnet link does -- leaves the
# process it started running inside the container, so a dispatch cut off
# mid-step goes on building. Every verb that starts work as uid 1000 (the
# container check before a sync, and each run) clears that first, so a retry
# never runs beside, or syncs under, the one it replaces. Nothing else runs as
# uid 1000 there: the container's own process is root's `sleep infinity`.
# The container runs under --init, so the orphans of a killed build are reaped
# rather than left as zombies of `sleep`; pgrep still counts only live states
# (-r R,S,D,T), because a zombie waiting for that reap is not a build that
# survived SIGKILL and must not fail the wait below.
# Expects $c (the container name) set in the VM-side script.
# shellcheck disable=SC2016  # expanded inside the VM, not here
REAP='
if nerdctl exec "$c" pgrep -r R,S,D,T -u 1000 >/dev/null 2>&1; then
  echo "[vm] killing a build left running in $c (a dispatch cut off mid-step)" >&2
  nerdctl exec "$c" pkill -KILL -u 1000 >/dev/null 2>&1 || true
  n=0
  while nerdctl exec "$c" pgrep -r R,S,D,T -u 1000 >/dev/null 2>&1; do
    n=$((n + 1))
    [ "$n" -le 30 ] || { echo "[vm] FATAL: uid 1000 processes in $c survive SIGKILL after 30 s" >&2; exit 1; }
    sleep 1
  done
fi
'

# relpath_ok <path>  -- a relative path with no `..`, spaces or shell syntax.
relpath_ok() {
  [[ "$1" =~ ^[A-Za-z0-9._/-]+$ ]] && [[ "$1" != /* ]] && [[ "/$1/" != */../* ]]
}

lima_status() {
  # `limactl list <name>` errors for a missing instance; the full list does not.
  limactl list --format '{{.Name}} {{.Status}}' 2>/dev/null \
    | awk -v n="$INSTANCE" '$1 == n { print $2; found = 1; exit } END { if (!found) print "absent" }'
}

# vm <script> [args...]  -- run a bash script inside the VM. The script goes
# in on stdin, so nothing but the plain-word arguments passes through
# limactl's command line.
vm() {
  local script="$1"; shift
  limactl shell --workdir / "$INSTANCE" bash -s "$@" <<<"$script"
}

do_status() {
  local v
  if ! command -v limactl >/dev/null 2>&1; then
    echo "limactl=missing"
  else
    v="$(limactl --version 2>/dev/null | awk '{ print $NF; exit }')"
    echo "limactl=${v:-unknown}"
  fi
  echo "arch=$(uname -m)"
  if [ -e /Library/Apple/usr/share/rosetta/rosetta ]; then echo "rosetta=yes"; else echo "rosetta=no"; fi
  if command -v limactl >/dev/null 2>&1; then
    echo "status=$(lima_status)"
    echo "others=$(lima_others "$INSTANCE" || echo unknown)"
  else
    echo "status=absent"
    echo "others=none"
  fi
  if [ ! -d "$LOCK_DIR" ]; then
    echo "lock=none"
  elif [ -f "$LOCK_DIR/owner" ]; then
    echo "lock=held"
    awk -F= '/^[a-z]+=/ { k = $1; sub(/^[^=]*=/, ""); print "lock." k "=" $0 }' "$LOCK_DIR/owner" 2>/dev/null || true
  else
    echo "lock=ownerless"
  fi
}

# --- the Mac build lock (protocol v1) -------------------------------------------
# One lock for the whole Mac, a directory in the build user's home: what two
# repos' linux legs share is the Mac's memory and disk, not any name
# (yaw-linux and oam-linux share none). mkdir is the atomic step; the owner
# file is written beside it and renamed into place, so a reader sees a whole
# owner or none. Whether a held lock may be taken over is decided from the
# owner's own instance alone: Running is BUSY; anything else (Stopped,
# missing, limactl erroring on it) means that run is over -- STALE. A lock
# whose owner file never appeared is a run mid-acquire for 60 s, STALE after.

# lima_others <instance>  -- the OTHER Running instances, comma-separated, or
# "none"; non-zero when limactl cannot list them.
lima_others() {
  local list
  list="$(limactl list --format '{{.Name}} {{.Status}}' 2>/dev/null)" || return 1
  awk -v n="$1" '$1 != n && $2 == "Running" { printf "%s%s", sep, $1; sep = "," } END { if (sep == "") printf "none" }' <<<"$list"
}

# owner_field <key>  -- one key of the owner file; empty when absent.
owner_field() {
  awk -F= -v k="$1" '$1 == k { sub(/^[^=]*=/, ""); print; exit }' "$LOCK_DIR/owner" 2>/dev/null || true
}

# lock_classify  -- the lock dir was there when this run's mkdir ran: sets
# LOCK_CLASS to busy, stale or gone (released meanwhile) and LOCK_OWNER to
# the owner on one line, for the message.
lock_classify() {
  local owner inst st mt age
  owner="$(cat "$LOCK_DIR/owner" 2>/dev/null || true)"
  if [ -n "$owner" ]; then
    LOCK_OWNER="$(printf '%s\n' "$owner" | tr '\n' ' ')"; LOCK_OWNER="${LOCK_OWNER% }"
    inst="$(owner_field instance)"
    st=""
    # A name that is not a Lima name is not an instance limactl could report
    # Running: stale, like a missing one. (It never reaches limactl's argv.)
    if [[ "$inst" =~ ^[A-Za-z0-9]([A-Za-z0-9-]*[A-Za-z0-9])?$ ]]; then
      st="$(limactl list --format '{{.Status}}' "$inst" 2>/dev/null | head -n1 || true)"
    fi
    if [ "$st" = "Running" ]; then LOCK_CLASS=busy; else LOCK_CLASS=stale; fi
    return 0
  fi
  if [ ! -d "$LOCK_DIR" ]; then LOCK_CLASS=gone; LOCK_OWNER="<released while it was read>"; return 0; fi
  # macOS stat: -f %m is the modification time in epoch seconds.
  mt="$(stat -f %m "$LOCK_DIR" 2>/dev/null || true)"
  if ! [[ "$mt" =~ ^[0-9]+$ ]]; then
    if [ ! -d "$LOCK_DIR" ]; then LOCK_CLASS=gone; LOCK_OWNER="<released while it was read>"; return 0; fi
    LOCK_CLASS=busy; LOCK_OWNER="<no owner file, and its age could not be read>"; return 0
  fi
  age=$(( $(date +%s) - mt ))
  if [ "$age" -gt 60 ]; then
    LOCK_CLASS=stale; LOCK_OWNER="<no owner file; the lock dir is ${age}s old>"
  else
    LOCK_CLASS=busy; LOCK_OWNER="<no owner file; the lock dir is ${age}s old -- another run is mid-acquire>"
  fi
}

lock_busy() {
  echo "[mac] BUSY: the Mac build lock ~/.lima-build.lock is held -- $1" >&2
  exit 3
}

# do_lock <runid> <repo> <instance> [<host> <pid>]
do_lock() {
  local run="${1:-}" repo="${2:-}" inst="${3:-}" host="${4:-unknown}" pid="${5:-0}" started others
  [[ "$run" =~ ^[A-Za-z0-9._-]+$ ]] || die "lock wants a run id of letters, digits, '.', '_' and '-', got '$run'"
  [[ "$repo" =~ ^(yaw|oam)$ ]] || die "lock wants the repo, yaw or oam, got '$repo'"
  [[ "$inst" =~ ^[A-Za-z0-9]([A-Za-z0-9-]*[A-Za-z0-9])?$ ]] || die "lock wants a Lima instance name, got '$inst'"
  [[ "$host" =~ ^[A-Za-z0-9._-]+$ ]] || die "lock wants a host name of letters, digits, '.', '_' and '-', got '$host'"
  [[ "$pid" =~ ^[0-9]+$ ]] || die "lock wants a pid, got '$pid'"
  command -v limactl >/dev/null 2>&1 || die "limactl is not on PATH -- brew install lima"
  if ! mkdir "$LOCK_DIR" 2>/dev/null; then
    lock_classify
    case "$LOCK_CLASS" in
      busy) lock_busy "$LOCK_OWNER" ;;
      stale)
        note "STALE Mac build lock (its VM is not Running): $LOCK_OWNER -- taking it over"
        rm -rf "$LOCK_DIR" ;;
      gone) note "the Mac build lock was released while it was read -- trying again" ;;
    esac
    # ONE retry; losing it means another run took the lock in between.
    if ! mkdir "$LOCK_DIR" 2>/dev/null; then
      lock_classify
      lock_busy "$LOCK_OWNER (taken while this run retried)"
    fi
  fi
  started="$(date -u +%Y-%m-%dT%H:%M:%SZ)"
  if ! printf 'repo=%s\ninstance=%s\nrun=%s\nhost=%s\npid=%s\nstarted=%s\n' \
       "$repo" "$inst" "$run" "$host" "$pid" "$started" > "$LOCK_DIR/owner.tmp" \
     || ! mv -f "$LOCK_DIR/owner.tmp" "$LOCK_DIR/owner"; then
    rm -rf "$LOCK_DIR"
    die "could not write the Mac build lock's owner file"
  fi
  # A VM started outside the protocol holds the memory all the same.
  if ! others="$(lima_others "$inst")"; then
    rm -rf "$LOCK_DIR"
    die "limactl cannot list the Lima instances, so a neighbour VM cannot be ruled out -- released the lock"
  fi
  if [ "$others" != "none" ]; then
    rm -rf "$LOCK_DIR"
    echo "[mac] BUSY: another Lima instance is Running on this Mac ($others) -- released the lock; it must stop first" >&2
    exit 3
  fi
  note "Mac build lock taken: repo=$repo instance=$inst run=$run host=$host pid=$pid started=$started"
}

# do_unlock <runid>  -- never removes another run's lock.
do_unlock() {
  local run="${1:-}" owner_run owner
  [[ "$run" =~ ^[A-Za-z0-9._-]+$ ]] || die "unlock wants a run id, got '$run'"
  if [ ! -d "$LOCK_DIR" ]; then note "no Mac build lock to release"; return 0; fi
  owner_run="$(owner_field run)"
  if [ -n "$owner_run" ] && [ "$owner_run" = "$run" ]; then
    rm -rf "$LOCK_DIR"
    note "Mac build lock released (run $run)"
    return 0
  fi
  owner="$(tr '\n' ' ' < "$LOCK_DIR/owner" 2>/dev/null || true)"
  echo "[mac] BUSY: not releasing the Mac build lock -- it belongs to another run: ${owner:-<no owner file>}" >&2
  exit 3
}

do_provision() {
  local cpus="${1:-}" mem="${2:-}" disk="${3:-}" st
  for n in "$cpus" "$mem" "$disk"; do
    [[ "$n" =~ ^[1-9][0-9]*$ ]] || die "provision wants three whole numbers (cpus, memory GiB, disk GiB), got '$cpus' '$mem' '$disk'"
  done
  command -v limactl >/dev/null 2>&1 || die "limactl is not on PATH -- brew install lima"
  st="$(lima_status)"
  if [ "$st" = "absent" ]; then
    note "creating $INSTANCE: vz, Rosetta, $cpus CPUs, ${mem} GiB memory, ${disk} GiB disk, Debian 12"
    limactl create --tty=false --name="$INSTANCE" --vm-type=vz --rosetta \
      --cpus="$cpus" --memory="$mem" --disk="$disk" template:debian-12 >&2
  else
    note "$INSTANCE exists ($st) -- re-applying its settings (the disk size is set at creation only)"
    if [ "$st" = "Running" ]; then limactl stop "$INSTANCE" >&2; fi
  fi
  # Same edits on a fresh and an existing instance, so a re-run converges.
  limactl edit --tty=false --set '.hostResolver.enabled = false' "$INSTANCE" >&2
  limactl edit --tty=false --set '.dns = ["1.1.1.1","8.8.8.8"]' "$INSTANCE" >&2
  limactl edit --tty=false --set ".cpus = $cpus | .memory = \"${mem}GiB\"" "$INSTANCE" >&2
  note "$INSTANCE provisioned (stopped)"
}

do_start() {
  local st
  st="$(lima_status)"
  case "$st" in
    Running) note "$INSTANCE already running" ;;
    absent) die "no Lima instance '$INSTANCE' on this Mac -- run the orchestrator with --provision" ;;
    *) note "starting $INSTANCE ($st)"; limactl start --tty=false "$INSTANCE" >&2 ;;
  esac
  vm 'true' || die "$INSTANCE started but a shell in it does not run"
}

do_stop() {
  local st
  st="$(lima_status)"
  case "$st" in
    Running) note "stopping $INSTANCE"; limactl stop "$INSTANCE" >&2 ;;
    *) note "$INSTANCE is $st -- nothing to stop" ;;
  esac
}

do_container() {
  local spec
  spec="$( (SPEC_SRC | shasum -a 256 2>/dev/null || SPEC_SRC | sha256sum) | cut -c1-16)"
  [[ "$spec" =~ ^[0-9a-f]{16}$ ]] || die "could not hash the container spec"
  # shellcheck disable=SC2016  # expanded inside the VM, not here
  vm '
set -euo pipefail
c="$1" vol="$2" spec="$3" image="$4" pkgs="$5" home="$6" nofile="$7"
mkdir -p "$HOME/.oam-linux"
printf "nameserver 1.1.1.1\nnameserver 8.8.8.8\n" > "$HOME/.oam-linux/resolv.conf"
# Right after limactl start the rootless containerd may still be coming up;
# wait for it (bounded) so a slow start is not read as anything else.
n=0
until nerdctl info >/dev/null 2>&1; do
  n=$((n + 1))
  [ "$n" -le 60 ] || { echo "[vm] FATAL: nerdctl cannot reach containerd 60 s after the VM started: $(nerdctl info 2>&1 | tail -1)" >&2; exit 1; }
  sleep 1
done
# Whether the container exists is asked of the listing, which succeeds
# either way; an inspect error past that point is a real failure, never
# "absent".
names="$(nerdctl container ls -a --format "{{.Names}}")" \
  || { echo "[vm] FATAL: nerdctl container ls failed" >&2; exit 1; }
running=absent
if printf "%s\n" "$names" | grep -qxF -- "$c"; then
  running="$(nerdctl container inspect --format "{{.State.Running}}" "$c")"
fi
if [ "$running" = "false" ]; then nerdctl start "$c" >/dev/null; running=true; fi
have=""
if [ "$running" = "true" ]; then have="$(nerdctl exec "$c" cat /etc/oam-spec 2>/dev/null || true)"; fi
if [ "$have" = "$spec" ]; then
  echo "[vm] container $c is current (spec $spec)" >&2
'"$REAP"'
else
  if [ "$running" != "absent" ]; then
    echo "[vm] container $c has spec ${have:-<none>}, want $spec -- recreating (the home volume $vol, and the build tree in it, stay)" >&2
    nerdctl rm -f "$c" >/dev/null
  fi
  echo "[vm] creating container $c from $image (linux/amd64)" >&2
  nerdctl run -d --init --name "$c" --network host --platform=linux/amd64 \
    --ulimit "nofile=$nofile:$nofile" \
    -v "$vol:$home" -v "$HOME/.oam-linux/resolv.conf:/etc/resolv.conf:ro" \
    "$image" sleep infinity >/dev/null
  arch="$(nerdctl exec "$c" uname -m)"
  [ "$arch" = "x86_64" ] || { echo "[vm] FATAL: the container runs as $arch, not x86_64 -- is Rosetta enabled for this instance?" >&2; exit 1; }
  nerdctl exec -e DEBIAN_FRONTEND=noninteractive "$c" sh -c "apt-get update -qq && apt-get install -y -qq $pkgs >/dev/null"
  nerdctl exec "$c" sh -c "id -u builder >/dev/null 2>&1 || useradd -u 1000 -d $home -M -s /bin/bash builder; chown 1000:1000 $home"
  nerdctl exec "$c" sh -c "echo $spec > /etc/oam-spec"
  echo "[vm] container $c ready (spec $spec)" >&2
fi
# Checked on every call, not assumed: under --network host nerdctl manages
# /etc/resolv.conf itself, and the dns conformance cases need the public
# servers only (the Lima forwarder answers no PTR or CAA). A mount that did
# not take would otherwise fail the leg ~40 minutes later in those cases.
ns="$(nerdctl exec "$c" awk "\$1 == \"nameserver\" { printf \"%s \", \$2 }" /etc/resolv.conf)"
[ "$ns" = "1.1.1.1 8.8.8.8 " ] || { echo "[vm] FATAL: $c resolves through [${ns% }], not [1.1.1.1 8.8.8.8] -- the resolv.conf bind mount did not take (the dns conformance cases would fail late)" >&2; exit 1; }
lim="$(nerdctl exec -u 1000 "$c" sh -c "ulimit -Hn")"
[ "$lim" = "$nofile" ] || { echo "[vm] FATAL: $c gives uid 1000 a hard open-file limit of $lim, not $nofile -- the flood tests need it" >&2; exit 1; }
echo "[vm] container $c: dns 1.1.1.1 8.8.8.8, nofile $lim" >&2
' "$CONTAINER" "$VOLUME" "$spec" "$IMAGE" "$PACKAGES" "$BUILD_HOME" "$NOFILE"
}

do_sync() {
  local rel="${1:-}"
  relpath_ok "$rel" || die "sync wants a Mac-home-relative tarball path, got '$rel'"
  [ -f "$HOME/$rel" ] || die "no tarball at ~/$rel on the Mac"
  # The VM reads the tarball through Lima's read-only mount of the Mac home,
  # at the same path as on the Mac.
  # shellcheck disable=SC2016
  vm '
set -euo pipefail
t="$1" c="$2" home="$3"
[ -r "$t" ] || { echo "[vm] FATAL: the VM cannot read $t -- Lima mounts the Mac home into the VM read-only at the same path; is that mount missing from the instance?" >&2; exit 1; }
nerdctl exec -i -u 1000 -w "$home" "$c" bash -c "mkdir -p oam-build && cd oam-build && find . -mindepth 1 -maxdepth 1 ! -name target -exec rm -rf {} + && tar xzf -" < "$t"
' "$HOME/$rel" "$CONTAINER" "$BUILD_HOME"
  rm -f "$HOME/$rel"
}

# The pinned Node goes FIRST on PATH for every dispatch, not only the oracle
# ones build-remote.sh pins itself: the e2e test for a pipe path with a NUL
# byte compares oam's answer with node's own, and Debian 12's node 18 answers
# differently from the pinned 22. prep provisions it at this path
# (scripts/lib/node-pin.sh, node_pin_dir); on prep's own first run the
# directory does not exist yet and PATH falls through to Debian's node and
# npm, which is all prep needs them for (installing tsgo into ~/.npm-oam).
do_run() {
  local d="${1:-}" nv="${2:-}"
  [[ "$d" =~ ^[a-z][a-z-]*$ ]] || die "run wants a dispatch name, got '$d'"
  [[ "$nv" =~ ^[0-9]+\.[0-9]+\.[0-9]+$ ]] || die "run wants the pinned Node version, got '$nv'"
  # shellcheck disable=SC2016
  vm '
set -euo pipefail
c="$1" d="$2" nv="$3" h="$4"
'"$REAP"'
exec nerdctl exec -u 1000 -w "$h/oam-build" -e HOME="$h" -e USER=builder -e LANG=C.UTF-8 \
  -e PATH="$h/.cache/oam-node/node-v$nv-linux-x64/bin:$h/.npm-oam/bin:$h/.cargo/bin:/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin" \
  "$c" bash scripts/build-remote.sh "$d"
' "$CONTAINER" "$d" "$nv" "$BUILD_HOME"
}

do_free_gb() {
  # shellcheck disable=SC2016
  vm 'exec nerdctl exec -u 1000 "$1" df -BG --output=avail "$2"' "$CONTAINER" "$BUILD_HOME"
}

do_glibc() {
  local rel="${1:-}"
  relpath_ok "$rel" || die "glibc wants a build-tree-relative path, got '$rel'"
  # objdump's own failure must reach the caller: grep alone would turn it into
  # an empty list, which the orchestrator then fails on without the reason.
  # shellcheck disable=SC2016
  vm '
exec nerdctl exec -u 1000 -w "$3/oam-build" "$1" sh -c "out=\$(objdump -T \"\$1\") || exit 1; printf \"%s\n\" \"\$out\" | grep -oE \"GLIBC_[0-9]+(\.[0-9]+)+\" | sort -u" sh "$2"
' "$CONTAINER" "$rel" "$BUILD_HOME"
}

do_fetch() {
  local rel="${1:-}" base sum mac_sum
  relpath_ok "$rel" || die "fetch wants a build-tree-relative path, got '$rel'"
  base="${rel##*/}"
  # Out of the container into the VM's own /tmp, then over to the Mac with
  # limactl copy: the Mac home is read-only from inside the VM.
  # shellcheck disable=SC2016
  sum="$(vm '
set -euo pipefail
c="$1" rel="$2" base="$3" h="$4" out=/tmp/oam-linux-out
rm -rf "$out"; mkdir -p "$out"
nerdctl exec -u 1000 -w "$h/oam-build" "$c" cat "$rel" > "$out/$base"
nerdctl exec -u 1000 -w "$h/oam-build" "$c" sha256sum "$rel" | cut -d" " -f1
' "$CONTAINER" "$rel" "$base" "$BUILD_HOME")" || die "could not copy ~/oam-build/$rel out of $CONTAINER"
  [[ "$sum" =~ ^[0-9a-f]{64}$ ]] || die "the container's sha256 of $rel is '$sum', not a hash"
  mkdir -p "$STAGE/out"
  rm -f "$STAGE/out/$base"
  limactl copy "$INSTANCE:/tmp/oam-linux-out/$base" "$STAGE/out/$base" >&2 \
    || die "limactl copy of $base out of $INSTANCE failed"
  mac_sum="$(shasum -a 256 "$STAGE/out/$base" | cut -d' ' -f1)"
  [ "$mac_sum" = "$sum" ] || die "$base changed on its way out of the VM: container sha256 $sum, Mac copy $mac_sum"
  echo "sha256=$sum"
  echo "path=.oam-linux-leg/out/$base"
}

main "$@"
