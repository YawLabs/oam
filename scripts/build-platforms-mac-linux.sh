#!/bin/bash
# =============================================================================
# oam linux-x64 platform-build orchestrator  (Lima VM on the build Mac)
# =============================================================================
# Runs the Linux leg in an x86_64 Debian 12 container, under Rosetta for Linux,
# inside a Lima VM on the build Mac -- the same tailnet Mac the mac legs use
# (scripts/build-platforms-tailnet.sh), reached the same way: OAM_MAC_HOST,
# OAM_MAC_USER, OAM_MAC_KEY. It replaced the cloud VM the linux leg used to
# run on. The Mac side (VM lifecycle, the container, copies in and out) is
# scripts/mac-linux-vm.sh, piped over ssh one verb at a time; its header says
# what the VM and the container are and why.
#
# x86_64 under Rosetta, not a native arm64 guest: oam cannot cross-compile
# (crates/oam_engine/build.rs -- the V8 startup snapshot must be generated by a
# process of the target architecture), so the build has to BE x86_64 code, the
# same trick the mac-x64 and win-x64 legs use. Debian 12, because it is the
# distro the linux asset has always been built on: the newest GLIBC_ symbol
# the binary needs is 2.34, so it runs on any glibc from 2.34 up. The build
# step is followed by a gate on exactly that (OAM_LINUX_GLIBC_MAX, below).
#
# Measured on the build Mac (8 GB Apple-Silicon Air, VM at 4 CPUs / 5 GiB,
# warm cargo cache): prep 19s, gate 338s, test ~700s, conformance ~800s,
# node-suite 314s, build 485s; a cold release build took 7m33s at a peak RSS of
# 1.6 GB, with no swap. The VM and the mac legs do not fit in memory together,
# so the VM is stopped whenever this script exits (OAM_KEEP_VM=1 keeps it),
# release-local.sh runs this leg after the mac legs, and --preflight-only
# stops a VM it finds running.
#
# The Mac build lock (protocol v1, shared with the Yaw repo's linux leg, which
# runs its own Lima instance on the same Mac): ~/.lima-build.lock on the Mac,
# one for the whole host -- what the two legs share is its memory and disk.
# Taken (mac-linux-vm.sh lock) before anything starts, stops or provisions a
# VM, in every mode including --preflight-only, and released (unlock, only
# ever this run's own) in the EXIT trap after the VM is stopped. Before it is
# taken, and again by the lock verb after, ANY other Lima instance Running on
# the Mac refuses the run: BUSY, exit non-zero, nothing stopped. A lock held
# by a run whose VM is Running is BUSY the same way; one whose VM is not
# Running is stale and taken over. The run id is <RUNID>-<pid>-<random>.
#
# Modes (each step is one `build-remote.sh <dispatch>` in the container):
#   --mode=release (default)
#       prep -> gate -> test -> conformance -> node-suite -> build
#       -> the glibc floor gate
#       pulls:  $ART/oam-x86_64-unknown-linux-gnu
#       (OAM_LINUX_FAST=1 skips gate/test/conformance/node-suite -- escape
#       hatch for a rebuild-only iteration; a real release never sets it)
#   --mode=measure
#       prep -> conformance -> node-suite   (advisory: a tripped gate warns,
#                                            scorecards still pulled)
#       pulls:  $ART/linux-x64/{scorecard.json,CONFORMANCE.md,
#                               node-suite-scorecard.json,CONFORMANCE-NODE.md}
#   --mode=bench
#       prep -> bench -> io-uring-ab
#       pulls:  $ART/linux-x64/{BENCHMARKS.md,results.json,io-uring-ab.log}
#       Numbers taken under Rosetta are directional at best: they describe
#       translated x86_64 code on an Apple core, not an x86_64 machine.
#   --mode=surface-gaps
#       prep -> surface-gaps; the whole conformance/surface-gaps.json comes
#       back into this checkout with its linux section re-measured
#
#   --preflight-only   with any mode: the key file, the Mac (resolves, answers,
#                      accepts the key), Lima on it (limactl present, Apple
#                      Silicon, Rosetta installed) and the instance -- and
#                      stop there. Prints nothing on stdout; exit 0 means a
#                      build could start. A VM found Running is stopped (the
#                      mac legs run next and need the memory) unless
#                      OAM_KEEP_VM=1. release-local.sh runs it before it tags.
#                      It takes the Mac build lock for that (always, so exit 0
#                      also means the lock was free) and always releases it:
#                      it never starts a VM. Another repo's VM Running, or the
#                      lock held by a run whose VM is Running, is BUSY: it
#                      exits non-zero and stops nothing. The one lock it
#                      clears itself is this repo's own left by an
#                      OAM_KEEP_VM=1 run on this same box whose process is
#                      gone (owner repo=oam, this instance, host=$(hostname),
#                      pid not alive here): it stops that VM, which makes the
#                      lock stale, then takes it -- the left-running VM is
#                      exactly what this stop is for. A build run does the
#                      same.
#   --provision        create the Lima instance if it is missing, and (re)apply
#                      its settings either way, before going on: limactl create
#                      --vm-type=vz --rosetta --cpus --memory --disk
#                      template:debian-12, then the resolver edits. Idempotent;
#                      an existing instance is stopped to be edited.
#
# Usage (FAIL-CLOSED -- capture first, check the exit, THEN consume):
#   ART=$(./scripts/build-platforms-mac-linux.sh) || { echo "linux leg failed"; exit 1; }
#   # The artifact dir path is the LAST stdout line; all progress goes to
#   # stderr, and each dispatch's whole output to its own log under the
#   # stage dir (the failure message names it).
#
# Host config (env):
#   OAM_MAC_HOST          the build Mac's tailnet name or IP     (required)
#   OAM_MAC_USER          the account on the Mac                 (required)
#   OAM_MAC_KEY           SSH key path (default ~/.ssh/yaw_mac_air, as the
#                         mac legs)
#   OAM_LIMA_INSTANCE     Lima instance name (default oam-linux); the
#                         container is <name>-build, its home volume
#                         <name>-home
#   OAM_LIMA_CPUS         4  )
#   OAM_LIMA_MEMORY_GIB   5  )  --provision only (the disk only at creation)
#   OAM_LIMA_DISK_GIB     80 )
#   OAM_LINUX_GLIBC_MAX   2.34 (default) -- the newest GLIBC_ symbol version
#                         the release binary may need. Over it, the leg fails:
#                         the asset would refuse to start on every distro
#                         older than the build image.
#   OAM_KEEP_VM=1         leave the VM running when this script exits
#                         (default: stop it, whatever state it was found in),
#                         and the Mac build lock held with it -- the release
#                         command is printed; the lock goes stale on its own
#                         once that VM is stopped
#   OAM_LINUX_FAST=1      see --mode=release
#   OAM_LINUX_RETRY_DELAY 15 (default) -- seconds to wait before the one
#                         retry a remote step gets when its ssh connection
#                         drops (ssh exits 255); see remote_step_run
#
# Prereqs on the Mac: Lima (brew install lima; 2.2.1 measured), Rosetta 2
# (the mac-x64 leg needs it too), outbound HTTPS from the VM. rustup, the
# pinned Rust toolchain, the pinned Node (.node-version) and tsgo are
# installed into the container's home volume by build-remote.sh prep on the
# first run, as on any build host.
# =============================================================================

set -euo pipefail

MODE="release"
PREFLIGHT_ONLY=0
PROVISION=0
for arg in "$@"; do
  case "$arg" in
    --mode=release|--mode=measure|--mode=bench|--mode=surface-gaps) MODE="${arg#--mode=}" ;;
    --preflight-only) PREFLIGHT_ONLY=1 ;;
    --provision) PROVISION=1 ;;
    -h|--help)
      awk 'NR==1{next} !/^#/{exit} {sub(/^# ?/, ""); print}' "$0"
      exit 0
      ;;
    *) echo "unknown arg: $arg (want --mode=release|measure|bench|surface-gaps, --preflight-only, --provision)" >&2; exit 1 ;;
  esac
done

RED='\033[0;31m'; GRN='\033[0;32m'; YEL='\033[1;33m'; CYA='\033[1;36m'; NC='\033[0m'
ok()  { echo -e "${GRN}  [ok]${NC} $*" >&2; }
warn(){ echo -e "${YEL}  [warn]${NC} $*" >&2; }
fail(){ echo -e "${RED}  [fail]${NC} $*" >&2; exit 1; }
step(){ echo -e "\n${CYA}=== $* ===${NC}" >&2; }

MAC_HOST="${OAM_MAC_HOST:-}"
MAC_USER="${OAM_MAC_USER:-}"
[ -n "$MAC_HOST" ] || fail "set OAM_MAC_HOST to the build Mac's tailnet name or IP (the linux leg runs in a VM on it)"
[ -n "$MAC_USER" ] || fail "set OAM_MAC_USER to the account on the build Mac (NOT \$USER from this box)"
MAC_KEY="${OAM_MAC_KEY:-$HOME/.ssh/yaw_mac_air}"
INSTANCE="${OAM_LIMA_INSTANCE:-oam-linux}"
LIMA_CPUS="${OAM_LIMA_CPUS:-4}"
LIMA_MEM="${OAM_LIMA_MEMORY_GIB:-5}"
LIMA_DISK="${OAM_LIMA_DISK_GIB:-80}"
GLIBC_MAX="${OAM_LINUX_GLIBC_MAX:-2.34}"
KEEP_VM="${OAM_KEEP_VM:-0}"
LINUX_FAST="${OAM_LINUX_FAST:-0}"
RETRY_DELAY="${OAM_LINUX_RETRY_DELAY:-15}"

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
REPO_DIR="$(cd "$SCRIPT_DIR/.." && pwd)"
# shellcheck source=lib/src-sync.sh
. "$SCRIPT_DIR/lib/src-sync.sh"
# disk_* thresholds and the df reading, last_nonblank_line.
# shellcheck source=lib/host-helpers.sh
. "$SCRIPT_DIR/lib/host-helpers.sh"
# tailnet_ssh_failure -- the same reading of a failed ssh as the mac legs.
# shellcheck source=lib/tailnet-helpers.sh
. "$SCRIPT_DIR/lib/tailnet-helpers.sh"
# shellcheck source=lib/linux-vm-helpers.sh
. "$SCRIPT_DIR/lib/linux-vm-helpers.sh"
# shellcheck source=lib/node-pin.sh
. "$SCRIPT_DIR/lib/node-pin.sh"
DRIVER="$SCRIPT_DIR/mac-linux-vm.sh"

# Every knob that reaches the Mac's command line is checked here, before
# anything touches the network: the remote shell must only ever see words.
lima_name_valid "$INSTANCE" \
  || fail "invalid OAM_LIMA_INSTANCE='$INSTANCE' (want letters, digits and inner hyphens)"
for knob in "OAM_LIMA_CPUS=$LIMA_CPUS" "OAM_LIMA_MEMORY_GIB=$LIMA_MEM" "OAM_LIMA_DISK_GIB=$LIMA_DISK"; do
  uint_valid "${knob#*=}" || fail "invalid ${knob%%=*}='${knob#*=}' (want a whole number, 1 or more)"
done
[[ "$RETRY_DELAY" =~ ^[0-9]+$ ]] \
  || fail "invalid OAM_LINUX_RETRY_DELAY='$RETRY_DELAY' (want a whole number of seconds)"
for knob in "OAM_KEEP_VM=$KEEP_VM" "OAM_LINUX_FAST=$LINUX_FAST"; do
  case "${knob#*=}" in 0|1) ;; *) fail "invalid ${knob%%=*}='${knob#*=}' (want 0 or 1)" ;; esac
done
# version_le against itself answers 2 exactly when it is not a version.
version_le "$GLIBC_MAX" "$GLIBC_MAX" \
  || fail "invalid OAM_LINUX_GLIBC_MAX='$GLIBC_MAX' (want a glibc version like 2.34)"
# The pin the container's PATH names (mac-linux-vm.sh run): the same file
# build-remote.sh provisions from, read on this side.
NODE_VERSION="$(node_pin_read "$REPO_DIR")" \
  || fail "cannot read the pinned Node from $REPO_DIR/.node-version (reason above)"
[ -f "$DRIVER" ] || fail "the Mac-side driver $DRIVER is missing"

RUNID="$(date +%Y%m%d-%H%M%S)"
HP="$MAC_USER@$MAC_HOST"
# The Mac build lock's owner: a run id no other run shares (RUNID is only to
# the second), and this box's name and this script's pid, each a plain word.
LOCK_RUN="$RUNID-$$-$RANDOM"
LOCK_HOST="$(hostname 2>/dev/null | tr -cd 'A-Za-z0-9._-')"
[ -n "$LOCK_HOST" ] || LOCK_HOST="unknown"
LOCK_PATH_HINT="ssh $HP 'rm -rf ~/.lima-build.lock'"
# Key-based NON-INTERACTIVE auth, as the mac legs: BatchMode fails a missing
# or rejected key fast instead of prompting on /dev/tty and hanging a
# background release. ServerAlive keeps a quiet 13-minute dispatch's
# connection up and notices a dead one.
SSH_OPTS=(-i "$MAC_KEY" -o IdentitiesOnly=yes -o BatchMode=yes -o StrictHostKeyChecking=accept-new -o ConnectTimeout=15 -o ServerAliveInterval=30 -o ServerAliveCountMax=10)

# mac_vm <verb> [args...]  -- one verb of the Mac-side driver, piped over ssh
# (the driver takes <verb> <instance> [args...]). Every argument is a
# validated word: the knobs above, dispatch names and paths written below.
mac_vm(){
  local verb="$1"; shift
  ssh "${SSH_OPTS[@]}" "$HP" "bash -s -- $verb $INSTANCE $*" < "$DRIVER"
}
# The lock verbs take their own arguments (protocol v1): exit 0 taken /
# released, 3 BUSY with the owner on stderr, anything else an error.
mac_lock(){
  ssh "${SSH_OPTS[@]}" "$HP" "bash -s -- lock $LOCK_RUN oam $INSTANCE $LOCK_HOST $$" < "$DRIVER"
}
mac_unlock(){
  ssh "${SSH_OPTS[@]}" "$HP" "bash -s -- unlock $LOCK_RUN" < "$DRIVER"
}

# One EXIT trap for every path, set before the first ssh. In order: the VM
# is stopped (once a build run holds the lock -- STOP_ON_EXIT -- unless
# OAM_KEEP_VM=1), then the lock is released, but only when the VM is known
# to be stopped or was never started by this run (a preflight): a lock left
# with a Running VM stays BUSY until that VM stops, then goes stale. Nothing
# here writes to stdout: the last stdout line is the artifact dir.
LOCK_HELD=0
STOP_ON_EXIT=0
STAGE_DIR=""
on_exit(){
  local stopped=1 log=/dev/stderr
  if [ "$STOP_ON_EXIT" = "1" ]; then
    if [ "$KEEP_VM" = "1" ]; then
      warn "OAM_KEEP_VM=1 -- leaving $INSTANCE running on $HP; stop it before the mac legs run: ssh $HP /opt/homebrew/bin/limactl stop $INSTANCE"
      stopped=0
    else
      [ -n "$STAGE_DIR" ] && log="$STAGE_DIR/logs/vm-stop.log"
      if mac_vm stop >"$log" 2>&1; then
        ok "stopped $INSTANCE on $HP"
      else
        warn "could not stop $INSTANCE on $HP (see $log) -- it is holding memory the mac legs need. On the Mac: limactl stop $INSTANCE"
        stopped=0
      fi
    fi
  fi
  [ "$LOCK_HELD" = "1" ] || return 0
  if [ "$stopped" = "1" ]; then
    local urc=0
    mac_unlock >&2 2>&1 || urc=$?
    case "$urc" in
      0) ok "released the Mac build lock (run $LOCK_RUN), or found none of this run's to release" ;;
      # The lock is another run's: this run never took it (the lock verb
      # failed before its mkdir won), so it is left alone.
      3) ok "the Mac build lock is not this run's (run $LOCK_RUN never took it) -- left alone" ;;
      *) warn "could not release the Mac build lock (run $LOCK_RUN; unlock exit $urc, see above) -- if it is still this run's: $LOCK_PATH_HINT" ;;
    esac
  else
    warn "leaving the Mac build lock (run $LOCK_RUN) held with $INSTANCE running: other runs see BUSY until it stops, then it is stale. To release it now: $LOCK_PATH_HINT"
  fi
}
trap on_exit EXIT
trap 'exit 130' INT
trap 'exit 143' TERM

# --- preflight ----------------------------------------------------------------
if [ "$PREFLIGHT_ONLY" = "1" ]; then
  step "Linux build host preflight -- Lima instance $INSTANCE on $HP"
else
  step "Run $RUNID -- oam linux-x64 --mode=$MODE in Lima instance $INSTANCE on $HP"
fi
[ -f "$MAC_KEY" ] || fail "Mac SSH key not found: $MAC_KEY -- the linux leg uses the mac legs' key (see scripts/build-platforms-tailnet.sh for the one-time setup), or point OAM_MAC_KEY at it"
if [ "$PREFLIGHT_ONLY" != "1" ]; then
  ( cd "$REPO_DIR" && git diff --quiet HEAD ) || warn "working tree dirty -- uncommitted changes WILL ship"
fi

# One BatchMode ssh answers whether the Mac resolves, answers and takes the
# key. The mac legs' preflight explains each failure at length (tailnet
# membership, Remote Login); this names the class and points there.
probe_out=$(ssh "${SSH_OPTS[@]}" "$HP" true 2>&1) || {
  probe_rc=$?
  probe_out="${probe_out//\\/\\\\}"
  probe_line="$(last_nonblank_line "$probe_out")" || probe_line="ssh exited $probe_rc and printed nothing"
  fail "ssh to $HP failed ($(tailnet_ssh_failure "$probe_out")): $probe_line\n  The linux leg reaches its VM through the build Mac, exactly as the mac legs do: scripts/build-platforms-tailnet.sh --preflight-only explains this failure in full."
}
ok "key auth OK on $HP"

STATUS_OUT="$(mac_vm status)" || fail "could not ask $HP about Lima (the driver's message is above)"
LIMACTL_V="$(kv_field "$STATUS_OUT" limactl || echo missing)"
MAC_ARCH="$(kv_field "$STATUS_OUT" arch || echo unknown)"
ROSETTA="$(kv_field "$STATUS_OUT" rosetta || echo no)"
VM_STATUS="$(kv_field "$STATUS_OUT" status || echo unknown)"
[ "$LIMACTL_V" != "missing" ] \
  || fail "Lima is not installed on $HP (limactl is not in /opt/homebrew/bin, /usr/local/bin or the ssh PATH) -- on the Mac: brew install lima"
[ "$MAC_ARCH" = "arm64" ] \
  || fail "$HP reports arch '$MAC_ARCH': the linux leg needs Apple Silicon (Rosetta for Linux runs the x86_64 build)"
[ "$ROSETTA" = "yes" ] \
  || fail "Rosetta 2 is not installed on $HP -- on the Mac: softwareupdate --install-rosetta --agree-to-license"
ok "Lima $LIMACTL_V on $HP; instance $INSTANCE is $VM_STATUS"
if [ "$PROVISION" != "1" ] && [ "$VM_STATUS" = "absent" ]; then
  fail "no Lima instance '$INSTANCE' on $HP -- create it once with: scripts/build-platforms-mac-linux.sh --provision --preflight-only"
fi

# --- the Mac build lock -----------------------------------------------------------
# lock_owner_line  -- the lock's owner as the status verb reported it, on one
# line ("" when the Mac reported no owner).
lock_owner_line(){
  local k v line=""
  for k in repo instance run host pid started; do
    v="$(kv_field "$STATUS_OUT" "lock.$k")" && line="$line $k=$v"
  done
  printf '%s' "${line# }"
}
OTHERS="$(kv_field "$STATUS_OUT" others || echo unknown)"
LOCK_STATE="$(kv_field "$STATUS_OUT" lock || echo unknown)"
case "$OTHERS" in
  none) ;;
  unknown|"") fail "$HP could not list its Lima instances, so a neighbour VM cannot be ruled out (the driver's status carries no others= answer)" ;;
  *)
    LOCK_NOTE=""
    [ "$LOCK_STATE" = "held" ] && LOCK_NOTE=" The Mac build lock is held by: $(lock_owner_line)."
    fail "BUSY: another Lima instance is Running on $HP ($OTHERS) -- the Mac's memory is in use by another build, so this run starts, stops and provisions nothing.$LOCK_NOTE" ;;
esac
# No self-heal before the lock: nothing here starts or stops a VM until this
# run holds it, and a pid recorded by another run cannot be judged from this
# box (WSL, Git Bash and other users each see their own pid namespace). A
# lock this repo left with OAM_KEEP_VM=1 is cleared by a human, with the two
# commands the BUSY message prints.
#
# LOCK_HELD is set BEFORE the lock verb runs: if the Mac takes the lock and
# the ssh connection then dies (255, or 130 on Ctrl-C), the EXIT trap still
# unlocks -- unlock removes only a lock whose owner is this run's id, so it
# is harmless when the Mac never took it. Only BUSY (3) clears it: the lock
# is another run's.
LOCK_HELD=1
LOCK_RC=0
LOCK_ERR="$(mac_lock 2>&1 >&2)" || LOCK_RC=$?
[ -z "$LOCK_ERR" ] || printf '%s\n' "$LOCK_ERR" >&2
case "$LOCK_RC" in
  0) ;;
  3)
    LOCK_HELD=0
    # The instance to stop: the owner's, as the Mac's answer names it, else
    # the one the status saw; the neighbour's when that is what refused.
    BUSY_INST=""
    [[ "$LOCK_ERR" =~ instance=([A-Za-z0-9]([A-Za-z0-9-]*[A-Za-z0-9])?) ]] && BUSY_INST="${BASH_REMATCH[1]}"
    if [ -z "$BUSY_INST" ] && [[ "$LOCK_ERR" =~ Running\ on\ this\ Mac\ \(([A-Za-z0-9-]+) ]]; then BUSY_INST="${BASH_REMATCH[1]}"; fi
    [ -n "$BUSY_INST" ] || BUSY_INST="$(kv_field "$STATUS_OUT" lock.instance || true)"
    lima_name_valid "${BUSY_INST:-x-}" || BUSY_INST="<the owner's instance>"
    BUSY_OWNER="$(lock_owner_line)"
    [ -n "$BUSY_OWNER" ] || BUSY_OWNER="see the Mac's answer above"
    fail "BUSY: the build Mac is in use by another run -- this run starts, stops and provisions nothing.\n  Owner: $BUSY_OWNER\n  If that run is over (for example a lock this repo left with OAM_KEEP_VM=1), clear it by hand:\n    ssh $HP /opt/homebrew/bin/limactl stop $BUSY_INST\n    $LOCK_PATH_HINT" ;;
  *) fail "could not take the Mac build lock on $HP (exit $LOCK_RC; the driver's message is above)" ;;
esac
ok "Mac build lock taken (run $LOCK_RUN)"
# A build run stops the VM on every exit from here on -- success, failure,
# Ctrl-C -- whatever state it was found in, unless OAM_KEEP_VM=1.
[ "$PREFLIGHT_ONLY" = "1" ] || STOP_ON_EXIT=1

if [ "$PROVISION" = "1" ]; then
  step "Provision Lima instance $INSTANCE ($LIMA_CPUS CPUs, ${LIMA_MEM} GiB memory, ${LIMA_DISK} GiB disk)"
  mac_vm provision "$LIMA_CPUS" "$LIMA_MEM" "$LIMA_DISK" >&2 \
    || fail "provisioning $INSTANCE on $HP failed -- see above"
  VM_STATUS="Stopped"
  ok "instance $INSTANCE provisioned"
fi

if [ "$PREFLIGHT_ONLY" = "1" ]; then
  if [ "$VM_STATUS" = "Running" ]; then
    if [ "$KEEP_VM" = "1" ]; then
      warn "$INSTANCE is Running and OAM_KEEP_VM=1 leaves it so -- the mac legs share that Mac's memory with it"
    else
      mac_vm stop >&2 || fail "$INSTANCE is Running on $HP and would not stop -- the mac legs need that memory. On the Mac: limactl stop $INSTANCE"
      ok "stopped $INSTANCE, found Running (the mac legs need the memory; OAM_KEEP_VM=1 leaves it)"
    fi
  fi
  exit 0
fi

STAGE_DIR_NEW="$(mktemp -d -t "oam-maclinux-build-$RUNID-XXXXXX")"
ARTIFACTS_DIR="$STAGE_DIR_NEW/artifacts"
mkdir -p "$STAGE_DIR_NEW/logs" "$ARTIFACTS_DIR"
STAGE_DIR="$STAGE_DIR_NEW"

# vm_step <log-name> <description> <verb> [args...]  -- a driver verb whose
# whole output goes to its own log; a failure prints the tail and ends the run.
vm_step(){
  local name="$1" what="$2"; shift 2
  local log="$STAGE_DIR/logs/$name.log"
  if mac_vm "$@" >"$log" 2>&1; then
    ok "$what"
  else
    tail -30 "$log" >&2
    fail "$what failed -- see $log"
  fi
}

step "Start $INSTANCE and its build container"
vm_step vm-start "$INSTANCE running" start
vm_step container "build container $INSTANCE-build ready" container

# --- source sync ----------------------------------------------------------------
# The tarball is what lib/src-sync.sh says ships (git's view of the tree, with
# its size ceiling), shared with the mac legs. It goes to the Mac first --
# the VM reads it through Lima's read-only mount of the Mac home -- and is
# extracted into the container's build tree, keeping target/: the warm cargo
# cache is the difference between a 7.5-minute cold release build and an
# incremental one.
MAC_STAGE=".oam-linux-leg"
step "Sync source -> $INSTANCE-build:~/oam-build (target/ preserved)"
SRC_TAR="$(mktemp "$STAGE_DIR/src-XXXXXX.tar.gz")" \
  || fail "could not create a staging tarball under $STAGE_DIR"
write_src_tarball "$REPO_DIR" "$SRC_TAR" \
  || fail "could not pack the source tree from $REPO_DIR -- is git healthy here? ('git ls-files' must work)"
SRC_BYTES="$(wc -c <"$SRC_TAR" 2>/dev/null | tr -dc '0-9')"
if src_tarball_over_ceiling "$SRC_BYTES"; then
  warn "biggest paths the sync would ship:"
  src_largest_paths "$REPO_DIR" 10 >&2 || true
  fail "source tarball is $((SRC_BYTES / 1048576))MB, over the ${OAM_SRC_TARBALL_MAX_MB}MB ceiling -- something is shipping build output. Check the paths above, then either clean them up or raise OAM_SRC_TARBALL_MAX_MB if the growth is legitimate."
fi
ok "source tarball: $((SRC_BYTES / 1024))KB (ceiling ${OAM_SRC_TARBALL_MAX_MB}MB)"
ssh "${SSH_OPTS[@]}" "$HP" "mkdir -p $MAC_STAGE" \
  || fail "could not create ~/$MAC_STAGE on $HP"
scp "${SSH_OPTS[@]}" -q "$SRC_TAR" "$HP:$MAC_STAGE/src.tar.gz" \
  || fail "scp of the source tarball to $HP failed"
vm_step sync "source extracted into $INSTANCE-build:~/oam-build" sync "$MAC_STAGE/src.tar.gz"
rm -f "$SRC_TAR"

# --- disk headroom ----------------------------------------------------------------
# After the sync, so the gc dispatch below is this run's build-remote.sh. The
# home volume sits on the VM's disk; a full one fails ~20 min into cargo with
# `os error 28`, which reads like a compiler bug.
step "Check build disk headroom"
read_build_disk(){  # sets DISK_FREE_GB; 1 (after a warning) when unreadable
  local out rc=0
  out="$(mac_vm free-gb 2>>"$STAGE_DIR/logs/free-gb.log")" || rc=$?
  if DISK_FREE_GB="$(disk_free_reading "$rc" "$out")"; then return 0; fi
  warn "build disk headroom NOT CHECKED: ${DISK_FREE_GB} (see $STAGE_DIR/logs/free-gb.log). A full disk will not fail here -- it fails ~20 min into cargo with 'os error 28'."
  DISK_FREE_GB=""
  return 1
}
if read_build_disk; then
  if disk_needs_reclaim "$DISK_FREE_GB"; then
    warn "the VM has ${DISK_FREE_GB}GB free -- reclaiming accreted cargo output before building"
    mac_vm run gc "$NODE_VERSION" >"$STAGE_DIR/logs/gc-pre.log" 2>&1 \
      || warn "pre-build reclaim failed (see $STAGE_DIR/logs/gc-pre.log) -- continuing to the threshold check"
    read_build_disk || true
  fi
  if disk_below_floor "$DISK_FREE_GB"; then
    fail "the VM still has only ${DISK_FREE_GB}GB free after reclaiming prunable cargo output -- a build needs ~7GB. Grow the instance's disk (limactl edit --set '.disk = ...'), or look for space outside ~/oam-build/target in the $INSTANCE-home volume."
  fi
  if [ -n "$DISK_FREE_GB" ]; then ok "build disk headroom: ${DISK_FREE_GB}GB free"; fi
fi

# --- remote steps ---------------------------------------------------------------
# remote_step_run <dispatch>: one `build-remote.sh <dispatch>` in the
# container, its whole output in its own log, the tail surfaced on failure.
#
# A dropped connection gets ONE retry of that step, not of the leg. ssh exits
# 255 for a connection-level failure (the tailnet link or the Mac's sshd went
# away, ServerAlive gave up) and passes any other exit code through from the
# remote command, so 255 is the one status that says the step itself did not
# fail. Without this, one blip during the ~800 s conformance step costs the
# whole leg again through release-local's OAM_RELEASE_LEG_ATTEMPTS: VM start,
# sync, prep, gate and test, ~45 minutes. The retry is safe to run because the
# driver's run verb first kills whatever the cut-off dispatch left running in
# the container (a dropped `nerdctl exec` client does not stop it), and every
# dispatch re-runs from scratch over the same tree. A second failure of any
# kind fails the step.
remote_step_run(){
  local dispatch="$1" log="$STAGE_DIR/logs/$1.log" rc=0
  mac_vm run "$dispatch" "$NODE_VERSION" >"$log" 2>&1 || rc=$?
  if [ "$rc" = "255" ]; then
    mv -f "$log" "$STAGE_DIR/logs/$dispatch.dropped.log"
    warn "remote '$dispatch': the ssh connection to $HP dropped (exit 255; that attempt's log: $STAGE_DIR/logs/$dispatch.dropped.log) -- retrying the step once in ${RETRY_DELAY}s"
    sleep "$RETRY_DELAY"
    rc=0
    mac_vm run "$dispatch" "$NODE_VERSION" >"$log" 2>&1 || rc=$?
  fi
  [ "$rc" = "0" ] && return 0
  tail -30 "$log" >&2
  return 1
}
remote_step(){
  remote_step_run "$1" || fail "remote '$1' failed -- see $STAGE_DIR/logs/$1.log"
  ok "remote $1 ok"
}
# Advisory: measurement scorecards and bench results are written BEFORE a
# tripped gate exits non-zero, so discarding them on failure loses the
# measurement.
remote_step_advisory(){
  if remote_step_run "$1"; then ok "remote $1 ok"
  else warn "remote '$1' failed (advisory -- continuing; see $STAGE_DIR/logs/$1.log)"; fi
}

# pull <build-tree-path> <local-dir>: out of the container to the Mac
# (mac-linux-vm.sh fetch, which checks the Mac copy against the container's
# sha256), then here into the stage dir, checked against the same hash, and
# only then moved into <local-dir> -- which for surface-gaps is a tracked file
# in this checkout, so a copy that fails the check must never land there.
sha256_of(){
  { sha256sum "$1" 2>/dev/null || shasum -a 256 "$1"; } | awk '{ print $1; exit }'
}
pull(){
  local rel="$1" dest="$2" out sum path got
  out="$(mac_vm fetch "$rel" 2>>"$STAGE_DIR/logs/pull.log")" \
    || fail "could not fetch $rel out of $INSTANCE-build (see $STAGE_DIR/logs/pull.log)"
  if ! sum="$(kv_field "$out" sha256)" || ! path="$(kv_field "$out" path)"; then
    fail "the Mac's answer to fetching $rel carries no sha256/path: $out"
  fi
  local base="${rel##*/}" pulled="$STAGE_DIR/pulled"
  mkdir -p "$pulled"
  rm -f "$pulled/$base"
  scp "${SSH_OPTS[@]}" -q "$HP:$path" "$pulled/" || fail "scp of $path from $HP failed"
  got="$(sha256_of "$pulled/$base")"
  [ "$got" = "$sum" ] \
    || fail "$rel arrived with sha256 ${got:-<none>}, but the container's copy is $sum -- refusing a file that changed on the way (left in $pulled, not in $dest)"
  mv -f "$pulled/$base" "$dest/$base" || fail "could not move the checked $base into $dest"
}

