case "$MODE" in
  release)
    if [ "$LINUX_FAST" = "1" ]; then
      warn "OAM_LINUX_FAST=1 -- skipping remote gate/test/conformance/node-suite (rebuild-only; NOT for a real release)"
    else
      remote_step gate
      remote_step test
      remote_step conformance
      # The one place the Linux node-suite ratchet gates.
      remote_step node-suite
    fi
    remote_step build
    # The glibc floor: the asset must start on every distro the build image's
    # glibc does, so the newest symbol version it binds may not move up. A
    # new dependency, or a newer image, would otherwise raise the floor
    # silently and the first to know would be a user on an older distro.
    step "glibc floor (newest GLIBC_ symbol <= $GLIBC_MAX)"
    GLIBC_OUT="$(mac_vm glibc dist/oam-x86_64-unknown-linux-gnu 2>"$STAGE_DIR/logs/glibc.log")" \
      || { cat "$STAGE_DIR/logs/glibc.log" >&2; fail "objdump -T could not read dist/oam-x86_64-unknown-linux-gnu in the container -- the glibc floor is NOT checked, so the binary does not ship"; }
    GLIBC_FOUND="$(glibc_max_version "$GLIBC_OUT")" \
      || fail "objdump -T found no GLIBC_ symbol versions in the linux binary -- a dynamically linked oam always has some, so this is a broken reading; the binary does not ship"
    if version_le "$GLIBC_FOUND" "$GLIBC_MAX"; then
      ok "newest GLIBC_ symbol: $GLIBC_FOUND (floor $GLIBC_MAX)"
    else
      fail "the linux binary needs GLIBC_$GLIBC_FOUND, newer than the $GLIBC_MAX floor (OAM_LINUX_GLIBC_MAX) -- it would not start on the distros the floor promises. Find what pulled the symbol in (objdump -T, then grep GLIBC_$GLIBC_FOUND), or raise the floor on purpose and say so in the release notes"
    fi
    step "Pull artifacts"
    pull "dist/oam-x86_64-unknown-linux-gnu" "$ARTIFACTS_DIR"
    ;;
  measure)
    remote_step_advisory conformance
    remote_step_advisory node-suite
    step "Pull scorecards"
    mkdir -p "$ARTIFACTS_DIR/linux-x64"
    pull "conformance/scorecard.json"            "$ARTIFACTS_DIR/linux-x64"
    pull "conformance/node-suite-scorecard.json" "$ARTIFACTS_DIR/linux-x64"
    pull "CONFORMANCE.md"                        "$ARTIFACTS_DIR/linux-x64"
    pull "CONFORMANCE-NODE.md"                   "$ARTIFACTS_DIR/linux-x64"
    ;;
  bench)
    remote_step bench
    # Advisory: an io_uring A/B failure must not discard the bench results
    # already written.
    remote_step_advisory io-uring-ab
    step "Pull bench results"
    mkdir -p "$ARTIFACTS_DIR/linux-x64"
