// A TLS server's key or PKCS#12 bundle protected with triple DES -- what
// `openssl rsa -des3` and OpenSSL 1.x's `pkcs8` / `pkcs12` wrote by default,
// and what many existing deployments still hold -- and the older ciphers Node
// 22 no longer reads: which createServer() opens, which it refuses and with
// what, and that tls and https servers then serve real Node clients with the
// key they opened.
//
// The client is a separate `node` process (the harness's oracle, on PATH) in
// BOTH runs, so only the server differs between them.
//
// Regression guard: oam had no DES implementation and refused every
// triple-DES-protected key and bundle with ERR_FEATURE_UNAVAILABLE_ON_PLATFORM,
// and reported the ciphers Node refuses (single DES, RC4, Blowfish) with
// other errors than Node's.
//
// Fixtures (OpenSSL 3.5; the single-DES, RC4 and Blowfish ones with its
// legacy provider): the case 150 P-256 CA and localhost leaf, and a
// self-signed RSA-2048 localhost certificate (2025-2125). The leaf's key as a
// legacy PEM key (`openssl ec -des3`, `-des-ede-cbc`, `-des`, `-bf`), the RSA
// key under `openssl rsa -traditional -des3`, PKCS#8 (`openssl pkcs8 -topk8
// -v2 des3` with PBKDF2-HMAC-SHA256 and -SHA1, `-v1 PBE-SHA1-3DES`, `-v1
// PBE-SHA1-2DES`, `-v2 des-cbc`, `-v1 PBE-SHA1-DES`, `-v1 PBE-MD5-DES`, `-v1
// PBE-SHA1-RC4-128`), and the pairs as PKCS#12 bundles (`openssl pkcs12
// -export` with `-keypbe` / `-certpbe` PBE-SHA1-3DES, PBE-SHA1-2DES,
// DES-EDE3-CBC, PBE-SHA1-RC4-128, DES-CBC and PBE-SHA1-DES, with and without
// a MAC, the CA included; one with an empty password). The passphrase is
// "hunter2" throughout.
