const pfx = (b64) => Buffer.from(b64, "base64");

const CLIENT = `
import tls from "node:tls";
const [ca, ops] = JSON.parse(process.argv[1]);
for (const op of ops) {
  const out = await new Promise((resolve) => {
    const s = tls.connect({ host: "127.0.0.1", port: op.port, servername: "localhost", ca }, () => {
      const peer = s.getPeerCertificate(true);
      const issuer = peer.issuerCertificate && peer.issuerCertificate !== peer ? peer.issuerCertificate.subject.CN : null;
      if (op.https) {
        let data = "";
        s.setEncoding("utf8");
        s.on("data", (d) => { data += d; });
        s.on("end", () => resolve({ authorized: s.authorized, subject: peer.subject.CN, bits: peer.bits, response: data.split("\\r\\n")[0] }));
        s.write("GET / HTTP/1.1\\r\\nHost: localhost\\r\\nConnection: close\\r\\n\\r\\n");
        return;
      }
      s.end();
      resolve({ authorized: s.authorized, subject: peer.subject.CN, bits: peer.bits, issuer });
    });
    s.on("error", (e) => resolve({ error: e.code }));
  });
  console.log(JSON.stringify(out));
}
`;
// The trusted certificates once, then one { port, https } per server.
function runClients(ca, ops) {
  return new Promise((resolve) => {
    const child = spawn("node", ["--input-type=module", "-e", CLIENT, JSON.stringify([ca, ops])], {
      stdio: ["ignore", "pipe", "inherit"],
    });
    let out = "";
    child.stdout.setEncoding("utf8");
    child.stdout.on("data", (d) => { out += d; });
    child.on("close", () => resolve(out.trim().split("\n").filter(Boolean)));
  });
}

